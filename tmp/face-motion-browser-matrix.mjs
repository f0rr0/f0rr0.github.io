import { chromium } from '/home/sid/.npm/_npx/e41f203b7505f1fb/node_modules/playwright-core/index.mjs';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
const browser = await chromium.launch({headless:true, executablePath:'/home/sid/.cache/ms-playwright/chromium-1223/chrome-linux64/chrome',args:['--no-sandbox']});
const out='build/face-motion-live/after';
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:2});
const portrait='[data-face-motion-frame]';
await page.goto('http://localhost:3109/resume');
await page.waitForFunction(()=>document.querySelector('[data-face-motion-frame]')?.dataset.faceMotionStatus==='ready');
const result={};
// Schedule the direction change within a single browser evaluation (not CDP round trips).
result.seam=await page.evaluate(async()=>{
  const stage=document.querySelector('[role="img"][data-face-motion-status]');
  const rect=stage.getBoundingClientRect();
  const move=(angle)=>window.dispatchEvent(new PointerEvent('pointermove',{pointerType:'mouse',clientX:rect.x+60+100*Math.cos(angle),clientY:rect.y+60+100*Math.sin(angle)}));
  const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  move(0);await wait(450);
  const p=document.querySelector('[data-face-motion-frame]');
  const frames=[];
  const observer=new MutationObserver(()=>{if(frames.at(-1)!==p.dataset.faceMotionFrame)frames.push(p.dataset.faceMotionFrame)});
  observer.observe(p,{attributes:true,attributeFilter:['data-face-motion-frame']});
  move(Math.PI/4);await wait(15);move(Math.PI/2);await wait(500);observer.disconnect();return frames;
});
assert.deepEqual(result.seam,['right_to_bottomright_1','right_to_bottomright_2','right_to_bottomright_3','bottom-right','bottomright_to_bottom_1','bottomright_to_bottom_2','bottomright_to_bottom_3','bottom']);
await page.mouse.move(1100,300);
await page.evaluate(()=>window.scrollTo(0,250));
await page.waitForTimeout(600);
result.scrollTarget=await page.locator(portrait).getAttribute('data-face-motion-target');
assert.equal(result.scrollTarget,'bottom');
await page.evaluate(()=>{window.scrollTo(0,0);document.documentElement.classList.add('dark');});
await page.waitForTimeout(300);
await page.screenshot({path:`${out}/dark-lockup.png`});
const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
await mobile.goto('http://localhost:3109/resume');
await mobile.waitForFunction(()=>document.querySelector('[data-face-motion-frame]')?.dataset.faceMotionStatus==='ready');
const stage=mobile.locator('[role="img"][data-face-motion-status]');
await stage.scrollIntoViewIfNeeded();
const rect=await stage.boundingBox();
const cdp=await mobile.context().newCDPSession(mobile);
await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:rect.x+60,y:rect.y+60}]});
await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:rect.x+180,y:rect.y+60}]});
await mobile.waitForTimeout(500);
result.touchFrame=await mobile.locator(portrait).getAttribute('data-face-motion-frame');
assert.equal(result.touchFrame,'right');
await mobile.screenshot({path:`${out}/mobile-lockup.png`});
await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
await mobile.waitForTimeout(500);
assert.equal(await mobile.locator(portrait).getAttribute('data-face-motion-frame'),'center');
const failure=await browser.newPage();
await failure.route('**/face-motion-atlas.webp*',route=>route.abort());
await failure.goto('http://localhost:3109/resume');
await failure.waitForFunction(()=>document.querySelector('[data-face-motion-frame]')?.dataset.faceMotionStatus==='degraded');
result.fallback=await failure.locator(portrait).getAttribute('data-face-motion-source');
assert.match(result.fallback,/poster/);
await page.goto('https://dahbiahmed.com/');
await page.screenshot({path:`${out}/reference-lockup.png`});
await writeFile(`${out}/matrix.json`,JSON.stringify(result,null,2));
await browser.close();
console.log(result);
